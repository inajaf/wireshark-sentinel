// MARK: - Result and errors

public struct BlockApplyResult: Sendable {
    public var output: String
    public var anchorPath: String
    public var appliedAt: Date

    public init(output: String, anchorPath: String, appliedAt: Date = Date()) {
        self.output = output
        self.anchorPath = anchorPath
        self.appliedAt = appliedAt
    }
}

public struct PrivilegedCommandError: Error, CustomStringConvertible, Sendable {
    public var message: String
    public var status: Int32?

    public init(message: String, status: Int32? = nil) {
        self.message = message
        self.status = status
    }

    public var description: String {
        if let status {
            return "\(message) (exit \(status))"
        }
        return message
    }
}

// MARK: - One administrator prompt

public protocol PrivilegedRunning: Sendable {
    func run(script: String) async throws -> String
}

/// Writes the script to a private temporary file and runs it through one
/// `osascript` administrator prompt. Every firewall change for one apply happens
/// inside that one script, so the person sees one password dialog, not five.
public struct AppleScriptAdminRunner: PrivilegedRunning, Sendable {
    public init() {}

    public func run(script: String) async throws -> String {
        try await Task.detached(priority: .userInitiated) {
            let directory = FileManager.default.temporaryDirectory
                .appendingPathComponent("sentinel-block-\(UUID().uuidString)", isDirectory: true)
            try FileManager.default.createDirectory(
                at: directory,
                withIntermediateDirectories: false,
                attributes: [.posixPermissions: 0o700]
            )
            defer { try? FileManager.default.removeItem(at: directory) }

            let file = directory.appendingPathComponent("apply.sh")
            try script.write(to: file, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: file.path)

            let command = "/bin/sh \(Self.shellQuote(file.path))"
            let apple = "do shell script \"\(Self.appleScriptEscape(command))\" with administrator privileges"

            let process = Process()
            process.executableURL = URL(fileURLWithPath: "/usr/bin/osascript")
            process.arguments = ["-e", apple]
            let pipe = Pipe()
            process.standardOutput = pipe
            process.standardError = pipe

            do {
                try process.run()
            } catch {
                throw PrivilegedCommandError(message: "could not start the administrator prompt: \(error)")
            }
            let data = pipe.fileHandleForReading.readDataToEndOfFile()
            process.waitUntilExit()
            let output = String(decoding: data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)

            guard process.terminationStatus == 0 else {
                throw PrivilegedCommandError(
                    message: output.isEmpty
                        ? "the administrator command failed. It may have been cancelled."
                        : output,
                    status: process.terminationStatus
                )
            }
            return output
        }.value
    }

    private static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    private static func appleScriptEscape(_ value: String) -> String {
        value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
    }
}

// MARK: - Controller

public struct PFBlockController: Sendable {
    public static let anchorPath = "/etc/pf.anchors/com.local.sentinel"
    public static let anchorName = "com.local.sentinel"

    private let runner: PrivilegedRunning

    public init(runner: PrivilegedRunning = AppleScriptAdminRunner()) {
        self.runner = runner
    }

    public func apply(plan: BlockPlan, persistAfterReboot: Bool) async throws -> BlockApplyResult {
        guard plan.isValid else {
            throw PrivilegedCommandError(
                message: "Refusing to apply an invalid block plan: \(plan.errors.joined(separator: "; "))"
            )
        }
        let script = Self.script(plan: plan, persistAfterReboot: persistAfterReboot)
        let output = try await runner.run(script: script)
        return BlockApplyResult(output: output, anchorPath: Self.anchorPath)
    }

    // MARK: Script generation

    public static func anchorText(plan: BlockPlan) -> String {
        var lines = [
            "# Wireshark Sentinel block anchor. Generated by the app; edits will be replaced.",
            "# Targets: \(plan.targets.map(\.displayName).joined(separator: ", "))",
            "",
        ]
        lines.append(contentsOf: plan.rules.map(\.text))
        lines.append("")
        return lines.joined(separator: "\n")
    }

    public static func script(plan: BlockPlan, persistAfterReboot: Bool) -> String {
        let anchor = anchorText(plan: plan)
        let hookLines = """
        anchor "com.local.sentinel"
        load anchor "com.local.sentinel" from "/etc/pf.anchors/com.local.sentinel"

        """
        let killLines = plan.killExistingStates
            ? plan.targets
                .map(\.address)
                .map { "pfctl -k \(shellQuote($0)) >/dev/null 2>&1 || true" }
                .joined(separator: "\n")
            : ""
        let persistence = persistAfterReboot ? "1" : "0"

        return """
        #!/bin/sh
        set -eu
        CONF=/etc/pf.conf
        ANCHOR=\(shellQuote(anchorPath))
        BACKUP=/etc/pf.conf.sentinel-backup
        HOOK=/etc/pf.conf.sentinel-hook
        DAEMON=/Library/LaunchDaemons/com.local.sentinel.pf.plist

        # Keep one pristine copy for troubleshooting and a current copy to roll
        # back to if this run fails.
        if [ ! -f "$CONF.sentinel-original" ]; then
            cp -p "$CONF" "$CONF.sentinel-original"
        fi
        cp -p "$CONF" "$BACKUP"

        mkdir -p /etc/pf.anchors
        umask 022
        cat > "$ANCHOR.new" <<'SENTINEL_ANCHOR_EOF'
        \(anchor)
        SENTINEL_ANCHOR_EOF
        chmod 644 "$ANCHOR.new"
        mv "$ANCHOR.new" "$ANCHOR"

        if ! grep -q '^anchor "com\\.local\\.sentinel"' "$CONF"; then
            cat > "$HOOK" <<'SENTINEL_HOOK_EOF'
        \(hookLines)
        SENTINEL_HOOK_EOF
            tmp="$CONF.sentinel-new"
            awk -v hookfile="$HOOK" '
                /^[[:space:]]*anchor[[:space:]]+"com[.]apple/ && !inserted {
                    while ((getline line < hookfile) > 0) print line
                    close(hookfile)
                    inserted = 1
                }
                { print }
                END {
                    if (!inserted) {
                        while ((getline line < hookfile) > 0) print line
                        close(hookfile)
                    }
                }
            ' "$CONF" > "$tmp"
            chmod 644 "$tmp"
            chown root:wheel "$tmp"
            mv "$tmp" "$CONF"
        fi

        if ! pfctl -n -f "$CONF" >/dev/null 2>&1; then
            cp -p "$BACKUP" "$CONF"
            echo "Sentinel: the modified pf.conf did not validate, so the original was restored." >&2
            exit 1
        fi

        if ! pfctl -f "$CONF"; then
            cp -p "$BACKUP" "$CONF"
            pfctl -f "$CONF" >/dev/null 2>&1 || true
            echo "Sentinel: pf rejected the ruleset, so the original pf.conf was restored." >&2
            exit 1
        fi

        pfctl -a com.local.sentinel -F rules >/dev/null 2>&1 || true
        pfctl -a com.local.sentinel -F Tables >/dev/null 2>&1 || true
        if ! pfctl -a com.local.sentinel -f "$ANCHOR"; then
            cp -p "$BACKUP" "$CONF"
            pfctl -f "$CONF" >/dev/null 2>&1 || true
            echo "Sentinel: the anchor did not load, so the original pf.conf was restored." >&2
            exit 1
        fi

        if ! pfctl -s info 2>/dev/null | grep -q 'Status: Enabled'; then
            pfctl -E >/dev/null 2>&1 || pfctl -e >/dev/null 2>&1 || true
        fi
        if ! pfctl -s info 2>/dev/null | grep -q 'Status: Enabled'; then
            echo "Sentinel: pf could not be enabled." >&2
            exit 1
        fi

        \(killLines)

        if [ "\(persistence)" = "1" ]; then
            cat > "$DAEMON" <<'SENTINEL_DAEMON_EOF'
        <?xml version="1.0" encoding="UTF-8"?>
        <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        <plist version="1.0">
        <dict>
            <key>Label</key>
            <string>com.local.sentinel.pf</string>
            <key>ProgramArguments</key>
            <array>
                <string>/sbin/pfctl</string>
                <string>-E</string>
                <string>-f</string>
                <string>/etc/pf.conf</string>
            </array>
            <key>RunAtLoad</key>
            <true/>
            <key>ProcessType</key>
            <string>Background</string>
        </dict>
        </plist>
        SENTINEL_DAEMON_EOF
            chmod 644 "$DAEMON"
            chown root:wheel "$DAEMON"
            launchctl bootout system "$DAEMON" >/dev/null 2>&1 || true
            launchctl bootstrap system "$DAEMON" >/dev/null 2>&1 || true
        else
            launchctl bootout system "$DAEMON" >/dev/null 2>&1 || true
            rm -f "$DAEMON"
        fi

        rm -f "$HOOK"
        echo "SENTINEL_ANCHOR_BEGIN"
        pfctl -a com.local.sentinel -sr
        echo "SENTINEL_ANCHOR_END"
        """
    }

    private static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}

// MARK: - Persistence of records and audit

public struct BlockStore: Sendable {
    public let url: URL

    public init(url: URL) {
        self.url = url
    }

    public func load() -> BlockState {
        guard let data = try? Data(contentsOf: url) else { return BlockState() }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return (try? decoder.decode(BlockState.self, from: data)) ?? BlockState()
    }

    public func save(_ state: BlockState) throws {
        let directory = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(
            at: directory,
            withIntermediateDirectories: true,
            attributes: [.posixPermissions: 0o700]
        )
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        let data = try encoder.encode(state)
        try data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
